import { chromium, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
  const context=await browser.newContext({viewport:{width:1440,height:1100}})
  const page=await context.newPage()
  const errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://127.0.0.1:5178')
  await page.getByRole('button',{name:'Build an insight',exact:true}).click()
  await expect(page.locator('.preview-count')).toContainText('20 students match')
  await expect(page.locator('.preview-count')).toContainText('2,000 problem sessions')
  await page.getByRole('combobox',{name:'Insight student'}).selectOption('STU-1020')
  await page.getByRole('combobox',{name:'Insight skill'}).selectOption('S06')
  await page.getByRole('button',{name:'60–80%',exact:true}).click()
  const min=page.getByRole('slider',{name:'Minimum accuracy'})
  const max=page.getByRole('slider',{name:'Maximum accuracy'})
  await min.focus()
  for(let i=0;i<5;i++)await page.keyboard.press('ArrowRight')
  await max.focus()
  for(let i=0;i<5;i++)await page.keyboard.press('ArrowLeft')
  await expect(min).toHaveValue('65')
  await expect(max).toHaveValue('75')
  await page.getByRole('radio',{name:/Summary/}).check()
  await page.getByRole('textbox',{name:'Additional focus'}).fill('Include exact correctness, hints, and confidence.')
  await expect(page.locator('.preview-count')).toContainText('1 student matches')
  await expect(page.locator('.preview-count')).toContainText('10 problem sessions')
  await expect(page.locator('.matching-students')).toContainText('Julian Reed70%')
  await expect(page.locator('.question-preview')).toContainText('Summarize the learning records for Julian Reed with 65–75% accuracy in Fraction operations')
  await page.screenshot({path:'/private/tmp/forma-insights-desktop.png',fullPage:true})
  const desktopAxe=await new AxeBuilder({page}).analyze()
  console.log('Desktop accessibility',JSON.stringify(desktopAxe.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))))
  expect(desktopAxe.violations).toEqual([])
  await page.getByRole('button',{name:'80–100%',exact:true}).click()
  await expect(page.locator('.preview-count')).toContainText('0 students match')
  await expect(page.getByRole('button',{name:'Generate insight'})).toBeDisabled()
  await page.getByRole('button',{name:'Reset',exact:true}).click()
  await expect(page.locator('.preview-count')).toContainText('20 students match')
  await expect(page.getByRole('combobox',{name:'Insight student'})).toHaveValue('')
  await expect(page.getByRole('combobox',{name:'Insight skill'})).toHaveValue('')
  await page.getByRole('button',{name:'0–60%',exact:true}).click()
  await page.getByRole('radio',{name:/Overview/}).check()
  await expect(page.locator('.question-preview')).toContainText('Give a learning overview')
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'/private/tmp/forma-insights-mobile.png',fullPage:true})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
  const mobileAxe=await new AxeBuilder({page}).analyze()
  expect(mobileAxe.violations).toEqual([])
  console.log('Mobile layout and accessibility passed')
  await page.setViewportSize({width:1440,height:1100})
  await page.getByRole('combobox',{name:'Insight student'}).selectOption('STU-1020')
  await page.getByRole('combobox',{name:'Insight skill'}).selectOption('S06')
  await page.getByRole('button',{name:'60–80%',exact:true}).click()
  await page.getByRole('radio',{name:/Summary/}).check()
  await expect(page.getByRole('button',{name:'Generate insight'})).toBeEnabled()
  const sent=page.waitForRequest('**/api/chat/stream')
  const started=Date.now()
  await page.getByRole('button',{name:'Generate insight'}).click()
  const request=(await sent).postDataJSON()
  expect(request.student_id).toBe('STU-1020')
  expect(request.filters).toEqual({skill_id:'S06',accuracy_min:60,accuracy_max:80,intent:'summary'})
  await expect(page.locator('.message.assistant .markdown')).toBeVisible({timeout:390000})
  console.log('Live first text seconds',(Date.now()-started)/1000)
  await expect(page.getByRole('button',{name:'New conversation'})).toBeEnabled({timeout:390000})
  const answer=await page.locator('.message.assistant .markdown').innerText()
  console.log('LIVE ANSWER',answer,'seconds',(Date.now()-started)/1000)
  expect(answer).toMatch(/70(?:\.0)?(?:%|\b)/)
  await expect(page.locator('.active-insight')).toContainText('Fraction operations · 60–80% · summary')
  await page.locator('.sources summary').click()
  await page.getByRole('button',{name:/FILTERED Selected students/}).click()
  await expect(page.getByRole('dialog')).toContainText('Julian Reed')
  await page.getByRole('button',{name:'Close dialog'}).click()
  await page.screenshot({path:'/private/tmp/forma-insights-answer.png',fullPage:true})
  // Verify follow-up scope without a second slow inference; the API filtering is covered separately.
  let followup
  await context.route('**/api/chat/stream',route=>{
    followup=route.request().postDataJSON()
    return route.fulfill({contentType:'text/event-stream',body:'event: delta\ndata: {"text":"Scoped follow-up."}\n\nevent: done\ndata: {"answer":"Scoped follow-up.","sources":[],"model":"Test","retrieval":{"query":"Scoped follow-up","retrieval_ms":0,"matches":[]},"metrics":{"cached":false,"total_ms":1}}\n\n'})
  })
  await page.getByRole('textbox',{name:'Ask about your students'}).fill('What about his confidence?')
  await page.getByRole('button',{name:'Send message'}).click()
  await expect(page.getByRole('button',{name:'New conversation'})).toBeEnabled()
  expect(followup.filters).toEqual(request.filters)
  expect(followup.history.length).toBeGreaterThan(0)
  await page.getByRole('button',{name:'Clear filters'}).click()
  await expect(page.locator('.active-insight')).toHaveCount(0)
  await page.getByRole('button',{name:'Build an insight',exact:true}).click()
  await expect(page.getByRole('slider',{name:'Minimum accuracy'})).toHaveValue('0')
  await expect(page.getByRole('slider',{name:'Maximum accuracy'})).toHaveValue('100')
  await context.route('**/api/insights/preview',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Preview temporarily unavailable.'})}))
  await page.getByRole('textbox',{name:'Additional focus'}).fill('Check preview recovery')
  await expect(page.getByRole('alert')).toContainText('Preview temporarily unavailable')
  await expect(page.getByRole('button',{name:'Generate insight'})).toBeDisabled()
  await context.unroute('**/api/insights/preview')
  await page.getByRole('button',{name:'Retry preview'}).click()
  await expect(page.getByRole('button',{name:'Generate insight'})).toBeEnabled()
  await page.getByRole('button',{name:'Skill library 12'}).click()
  await page.getByRole('button',{name:/01.*Combining like terms/}).click()
  await expect(page.getByRole('textbox',{name:'Ask about your students'})).toBeVisible()
  expect(errors).toEqual([])
  console.log('Guided insights, no-match, reset, strict request filters, live generation, sources, and follow-up passed')
} finally {await browser.close()}
